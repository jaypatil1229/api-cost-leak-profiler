// src/types.ts

export type Provider = "OPENAI" | "GEMINI";

export type EventStatus = "SUCCESS" | "ERROR" | "TIMEOUT";

export interface UsageEvent {
  /** Unique identifier for the event, max 128 chars */
  eventId: string;
  /** Provider name, must be uppercase */
  provider: Provider;
  /** Model name, max 120 chars */
  model: string;
  /** ISO timestamp when the event occurred */
  occurredAt: string;
  /** Token counts */
  inputTokens: number;
  outputTokens: number;
  /** Total tokens (sum of input+output; auto-computed if not provided) */
  totalTokens: number;
  /** Optional cached input token count */
  cachedInputTokens?: number;
  /** Optional latency in ms */
  latencyMs?: number;
  /** Status of the request */
  status?: EventStatus;
  /** Optional error code */
  errorCode?: string;
  /** External request identifier (e.g., OpenAI request ID) */
  externalRequestId?: string;
  /** Optional feature identifier for grouping */
  featureId?: string;
  /** Optional customer user identifier */
  customerUserId?: string;
  /** Optional session identifier */
  sessionId?: string;
  /** SHA256 hash of the prompt (privacy) */
  promptHash?: string;
  /** Prompt character count */
  promptCharCount?: number;
  /** Completion character count */
  completionCharCount?: number;
  /** Arbitrary metadata (max 32 entries) */
  metadata?: Record<string, string>;
}

export interface AclpClientConfig {
  /** The raw project API key generated by the ACLP backend (includes prefix) */
  apiKey: string;
  /** The projectId the events belong to */
  projectId: string;
  /** Base URL of the backend (default http://localhost:3000) */
  baseUrl?: string;
  /** Whether the SDK should automatically send batches */
  enabled?: boolean;
  /** Interval in ms to flush the queue (default 5000) */
  flushIntervalMs?: number;
  /** Maximum number of events per batch (default 200, max 500) */
  maxBatchSize?: number;
  /** Maximum number of events retained in memory before dropping oldest (default 10000) */
  maxQueueSize?: number;
}
